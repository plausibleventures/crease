// Tool policy for a project's Claude Code session (R01). Three layers, outermost first:
//   1. OS sandbox for Bash (sandbox.ts): the real boundary for shell commands and everything they start.
//   2. PreToolUse hook (policyHooks): runs checkTool() for EVERY tool call, including subagents' calls and calls a
//      settings allow rule would otherwise auto-approve. A hook "deny" wins over any allow rule.
//   3. canUseTool (makeCanUseTool): the same checkTool() again, plus AskUserQuestion routing.
// Layers 2-3 are in-harness checks with helpful messages; the Bash checks below are heuristics that explain the
// obvious cases early. The sandbox is what actually stops interpreters, symlinks and network from the shell.
import { relative, resolve, sep } from "node:path"
import type { CanUseTool, HookCallbackMatcher, HookEvent, PermissionResult } from "@anthropic-ai/claude-agent-sdk"
import { canonicalPath, expandHome, isInside, realRoot } from "../projects/paths"
import { lookup } from "node:dns/promises"
import { isIP } from "node:net"
import { readOutsideReason } from "./readscope"

// Canonical containment (symlinks resolved) lives in projects/paths.ts, shared with the HTTP routes and studio tools.
export { canonicalPath, isInside }

const WRITE_TOOLS = new Set(["Write", "Edit", "NotebookEdit", "MultiEdit"])

const RESLICE =
  "G-code and slice files are generated by the slicer and must never be edited by hand (the printer would run " +
  "something nobody reviewed). To change how it prints, re-slice: slice_part, or slice_plate with per-part " +
  "settings in parts[].overrides. To change the shape, edit parts/*.scad and render again."

/**
 * Why writing `p` is not allowed, or null. Checks the canonical path (symlinks resolved) against the project folder
 * and Crease's own files at any depth.
 */
export function protectedReason(root: string, p: string): string | null {
  const base = realRoot(root)
  const abs = canonicalPath(root, p)
  if (!isInside(base, abs)) {
    const lexical = resolve(root, expandHome(p))
    return isInside(resolve(root), lexical) || isInside(base, lexical)
      ? `${p} goes through a symlink that leads outside the project folder; write the real file inside the project instead.`
      : `Writes are only allowed inside the project folder (${base}); ${p} is outside it.`
  }
  const parts = relative(base, abs).split(sep).filter(Boolean)
  const top = parts[0] ?? ""
  if (/\.(gcode|bgcode|gco|g)$/i.test(abs) || (top === "build" && /\.3mf$/i.test(abs))) return RESLICE
  if (parts.includes(".git")) return "Version history is managed by Crease. Use save_checkpoint to save a version; don't touch .git/."
  if (parts.includes(".studio")) return ".studio/ holds Crease's sessions, checks and approvals; it can't be edited. Use the studio tools instead."
  if (parts.includes(".claude") || top === ".mcp.json" || /^CLAUDE(\.local)?\.md$/i.test(parts[parts.length - 1] ?? "")) return "The assistant's own settings, instructions (CLAUDE.md) and skills are managed by Crease and can't be changed from a session."
  if (top === "build" || top === "renders")
    return `${top}/ is generated by Crease (renders, meshes, slice output). Edit parts/*.scad (or a Blender part's parts/*.blend.py) or lib/ and run render_part / slice_part again instead.`
  if (top === "parts" && parts[1] === "imported" && /\.(stl|3mf|json)$/i.test(abs))
    return "Imported meshes and their source/licence records are kept as the user imported them. Scale it with scale_percent (set_parameters), lay it differently with set_orientation, or model a new part in parts/*.scad instead."
  if (top === "project.json" && parts.length === 1)
    return "project.json is managed by Crease: new parts/*.scad and parts/*.blend.py files register themselves; use set_parameters, update_assembly or set_target_machine for the rest."
  return null
}

const BLENDER_MSG =
  "Blender runs only through Crease: write the part as parts/<id>.blend.py (see the blender-sculpting skill) " +
  "and call render_part; the app runs the script in Blender's sandbox and shows you the pictures and any error"

const NET_MSG =
  "the design assistant has no network access from the shell. Printers are reached only through Crease's " +
  "tools (slice_part / slice_plate, then request_print); never contact a printer directly"

export interface PolicyOptions {
  /** Printer hosts (machines.json); commands or fetches naming one are refused. */
  printerHosts?: string[]
  /** App files holding secrets (settings.json, secrets.json); Read/Grep/Glob of them, or of a folder containing them, are refused. */
  denyRead?: string[]
  /**
   * Folders outside the project Read/Grep/Glob may read (readscope.ts: app skills, bundled libraries, the runtime's
   * session folders). Set = reads anywhere else are refused; unset = no read boundary (tests of other rules).
   */
  readRoots?: string[]
  /** DNS for the WebFetch check (tests); default: the system resolver. */
  resolveHost?: HostResolver
}

const READ_TOOLS = new Set(["Read", "Grep", "Glob", "NotebookRead"])

function readDenied(root: string, raw: string | undefined, opts: PolicyOptions): boolean {
  if (!raw || !opts.denyRead?.length) return false
  const p = canonicalPath(root, raw)
  return opts.denyRead.some((f) => {
    const target = canonicalPath(root, f)
    return p === target || isInside(p, target)
  })
}

function escapeRe(s: string) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
}

/** Returns a denial reason, or null if the command is allowed. Heuristic: the OS sandbox is the real boundary. */
export function checkBash(root: string, command: string, opts: PolicyOptions = {}): string | null {
  const cmd = command.trim()
  const deny: [RegExp, string][] = [
    [/\bsudo\b/, "sudo is not allowed"],
    [/\bgit\s+(push|remote\s+(add|set-url))\b/, "pushing or adding git remotes is not allowed"],
    [/\bgit\s+(reset\s+--hard|clean\s+-[a-z]*f|filter-branch|rebase)\b/, "history-rewriting or destructive git commands are not allowed; use save_checkpoint"],
    [/\bgit\s+(commit|add|checkout|switch|restore|reset|stash|merge|cherry-pick|revert|tag|branch\s+-[dDmM]|rm|mv|config|init|gc|update-ref|worktree)\b/, "version history is managed by Crease; use save_checkpoint (git is read-only here: status, log, diff, show)"],
    [/\b(curl|wget)\b[^|]*\|\s*(ba|z)?sh\b/, "piping downloads into a shell is not allowed"],
    [/\b(mkfs|dd|diskutil|shutdown|reboot|launchctl|chmod\s+-R|chown|osascript)\b/, "system-level commands are not allowed"],
    [/:\(\)\s*\{/, "fork bombs are not allowed"],
    // Blender part scripts run only through the app, in Blender's own sandbox (server/cad/blender.ts).
    [/(^|[\s|;&(`'"/])blender(\s|$|["'])/i, BLENDER_MSG],
    [/(^|[|;&(`]\s*|\b(xargs|env|exec|nohup|time|command|sh -c|bash -c)\s+["']?)(curl|wget|nc|ncat|netcat|telnet|ssh|scp|sftp|rsync|ftp|socat|websocat|http|https|xh|aria2c|git\s+(fetch|pull|clone|ls-remote))\b/, NET_MSG],
    [/\bfetch\s*\(|\bnew\s+(XMLHttpRequest|WebSocket)\b|\burlopen\b|\burllib\b|\brequests\.(get|post|put|request)\b|\bhttp\.client\b|\bhttps?\.(get|request)\s*\(|\bsocket\.(socket|create_connection)\b|\bnet\.connect\b|Net::HTTP|LWP::/, NET_MSG],
    [/\bmoonraker\b|\/printer\/(print|gcode|objects|info|emergency_stop|firmware_restart|restart)\b|\/server\/files\/upload\b|\/machine\/(reboot|shutdown)\b/i, NET_MSG],
    [/(?:\b\d{1,3}(?:\.\d{1,3}){3}|localhost|\[[0-9a-f:]+\]):\d{2,5}\b/i, NET_MSG],
  ]
  for (const host of opts.printerHosts ?? []) if (host) deny.push([new RegExp(`(^|[^\\w.-])${escapeRe(host)}([^\\w.-]|$)`, "i"), NET_MSG])
  for (const [re, why] of deny) if (re.test(cmd)) return why

  // Paths used by destructive commands or redirects must stay inside the project folder and off app-owned files.
  const destructive = /\b(rm|rmdir|mv|cp|ln|truncate|shred|tee|touch|mkdir|unlink|install|sed\s+-i|perl\s+-[a-z]*i|patch|tar|unzip|ditto|rsync)\b/.test(cmd)
  const tokens = cmd.match(/(?:>>?\|?\s*)?(?:"[^"]*"|'[^']*'|[^\s;&|()<>]+)/g) ?? []
  for (const raw of tokens) {
    const isRedirect = /^>>?/.test(raw)
    const tok = raw.replace(/^>>?\|?\s*/, "").replace(/^["']|["']$/g, "")
    if (!(destructive || isRedirect) || !tok || tok.startsWith("-")) continue
    if (tok === "/dev/null" || tok === "/dev/stdout" || tok === "/dev/stderr" || /^&\d$/.test(tok)) continue
    if (!isRedirect && !(tok.startsWith("/") || tok.startsWith("~") || tok.includes("..") || tok.includes("/") || /\.(gcode|bgcode|3mf)$/i.test(tok) || PROTECTED_TOP.test(tok))) continue
    const why = protectedReason(root, tok)
    if (why) return why
  }
  // Interpreters writing files: catch the obvious "python3 -c open('build/x.gcode','w')" style.
  if (/\b(python3?|node|deno|bun|perl|ruby|php|lua|osascript|awk|gawk)\b/.test(cmd) && /(['"](w|a|wb|ab|w\+|r\+)['"]|write(File|FileSync|_text|_bytes)?\b|appendFile|unlink|rename|remove|rmtree|copyfile|copy2?|move|symlink|truncate|mkdir)/.test(cmd)) {
    for (const m of cmd.matchAll(/(?<=["'`])([^"'`\s]+)(?=["'`])/g)) {
      const p = m[1]
      if (!(p.includes("/") || p.includes("."))) continue
      if (!(PROTECTED_TOP.test(p) || /\.(gcode|bgcode|3mf)$/i.test(p) || p.startsWith("/") || p.startsWith("~") || p.includes(".."))) continue
      const why = protectedReason(root, p)
      if (why) return why
    }
  }
  if (/\brm\s+-[a-zA-Z]*r[a-zA-Z]*\s+(\.\/?|\*)\s*$/.test(cmd)) return "refusing to delete the whole project folder"
  return null
}
const PROTECTED_TOP = /^(\.\/)?(build|renders|\.studio|\.git|\.claude|\.mcp\.json|project\.json|CLAUDE(\.local)?\.md)(\/|$)/

const PRIVATE_HOST = /^(localhost|.*\.local|.*\.localhost|.*\.internal|.*\.lan|.*\.home\.arpa|0\.0\.0\.0|127\.\d+\.\d+\.\d+|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+|169\.254\.\d+\.\d+|100\.(6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d+\.\d+|\[?::1\]?|\[?f[cd][0-9a-f]{2}:.*|\[?fe80:.*)$/i

/** WebFetch may read the public web (docs, datasheets) but never the local network: printers, the app, routers. */
export function checkFetchUrl(url: string, opts: PolicyOptions = {}): string | null {
  let host: string
  try {
    host = new URL(url).hostname.toLowerCase()
  } catch {
    return null // not a URL; the tool rejects it itself
  }
  const hosts = (opts.printerHosts ?? []).map((h) => h.toLowerCase())
  if (hosts.includes(host) || PRIVATE_HOST.test(host) || !host.includes(".") || /^\d+$/.test(host)) return NET_MSG
  return null
}

const v4 = (ip: string) => ip.split(".").map(Number)

/** Loopback, private, link-local, CGNAT, multicast, reserved or unspecified (IPv4, IPv6, IPv4-mapped/NAT64 IPv6). */
export function isPrivateAddress(ip: string): boolean {
  const kind = isIP(ip)
  if (kind === 4) {
    const [a, b] = v4(ip)
    return (
      a === 0 || a === 10 || a === 127 || a >= 224 || // this-network, private, loopback, multicast + reserved
      (a === 100 && b >= 64 && b <= 127) || // CGNAT
      (a === 169 && b === 254) || // link-local (cloud metadata too)
      (a === 172 && b >= 16 && b <= 31) ||
      (a === 192 && b === 168) ||
      (a === 192 && b === 0 && v4(ip)[2] === 0) || // IETF protocol assignments
      (a === 198 && (b === 18 || b === 19)) // benchmarking
    )
  }
  if (kind !== 6) return true // not an address: treat as unsafe
  const s = ip.toLowerCase().replace(/^\[|\]$/g, "").replace(/%.*$/, "")
  const mapped = s.match(/^(?:::ffff:|64:ff9b::)(\d+\.\d+\.\d+\.\d+)$/)
  if (mapped) return isPrivateAddress(mapped[1])
  const hexMapped = s.match(/^(?:::ffff:|64:ff9b::)([0-9a-f]{1,4}):([0-9a-f]{1,4})$/)
  if (hexMapped) {
    const n = (parseInt(hexMapped[1], 16) << 16) | parseInt(hexMapped[2], 16)
    return isPrivateAddress([n >>> 24, (n >>> 16) & 255, (n >>> 8) & 255, n & 255].join("."))
  }
  if (s === "::" || s === "::1") return true
  const first = parseInt(s.split(":")[0] || "0", 16)
  return (first & 0xfe00) === 0xfc00 || (first & 0xffc0) === 0xfe80 || (first & 0xff00) === 0xff00 // ULA, link-local, multicast
}

/** All addresses a host name resolves to (overridable in tests). */
export type HostResolver = (host: string) => Promise<string[]>
const systemResolver: HostResolver = async (host) => (await lookup(host, { all: true, verbatim: true })).map((a) => a.address)

/**
 * checkFetchUrl plus DNS: the host name is resolved and every address must be public and not a printer's (a public
 * name can point at 10.0.0.24 or 127.0.0.1). A name that doesn't resolve is refused too. (WebFetch resolves again
 * when it connects, so a rebinding name could still switch in between; the shell has no network at all.)
 */
export async function checkFetchUrlResolved(url: string, opts: PolicyOptions = {}, resolver: HostResolver = opts.resolveHost ?? systemResolver): Promise<string | null> {
  const byName = checkFetchUrl(url, opts)
  if (byName) return byName
  let host: string
  try {
    host = new URL(url).hostname.toLowerCase().replace(/^\[|\]$/g, "")
  } catch {
    return null
  }
  const resolveAll = async (h: string) => (isIP(h) ? [h] : await resolver(h))
  let addrs: string[]
  try {
    addrs = await resolveAll(host)
  } catch {
    return `couldn't look up ${host}, so it can't be checked; only public websites can be fetched`
  }
  if (!addrs.length || addrs.some(isPrivateAddress)) return NET_MSG
  const printerAddrs = new Set<string>()
  for (const h of opts.printerHosts ?? []) {
    try {
      for (const a of await resolveAll(h.toLowerCase())) printerAddrs.add(a)
    } catch {
      /* a printer name that doesn't resolve can't match */
    }
  }
  return addrs.some((a) => printerAddrs.has(a)) ? NET_MSG : null
}

/**
 * Claude Code tools a design session never uses: scheduling and wake-ups, remote triggers, worktrees, workflows,
 * push notifications, team/agent messaging, design sync, review reporting and plan mode. Passed as the session's
 * disallowedTools (they leave the model's tool list) and denied by checkTool as well (subagents, future aliases).
 * Kept: Bash, Read/Write/Edit, Glob/Grep, Task/Agent (subagents), the task list (TodoWrite / Task*), Monitor,
 * ToolSearch, WebSearch/WebFetch, Skill, AskUserQuestion and the studio MCP tools.
 */
export const DESIGN_DISALLOWED_TOOLS = [
  "CronCreate",
  "CronDelete",
  "CronList",
  "ScheduleWakeup",
  "RemoteTrigger",
  "EnterWorktree",
  "ExitWorktree",
  "Workflow",
  "PushNotification",
  "SendMessage",
  "ListAgents",
  "TeamCreate",
  "TeamDelete",
  "DesignSync",
  "ReportFindings",
  "EnterPlanMode", // plan mode would stop every edit until someone approves the plan; nobody is at a terminal
  "ExitPlanMode",
] as const
const DISALLOWED = new Set<string>(DESIGN_DISALLOWED_TOOLS)

/**
 * The single policy check, shared by the PreToolUse hook and canUseTool. Returns a denial message for the agent
 * (always saying what to do instead), or null to let the call through.
 */
export function checkTool(root: string, toolName: string, input: Record<string, unknown>, opts: PolicyOptions = {}): string | null {
  const why = checkToolInner(root, toolName, input, opts)
  return why && why.replace(/\.\.$/, ".")
}

/** checkTool plus the checks that need I/O (WebFetch: DNS). Used by the PreToolUse hook and canUseTool. */
export async function checkToolAsync(root: string, toolName: string, input: Record<string, unknown>, opts: PolicyOptions = {}): Promise<string | null> {
  const why = checkTool(root, toolName, input, opts)
  if (why || toolName !== "WebFetch") return why
  const dns = await checkFetchUrlResolved(String(input.url ?? ""), opts)
  return dns ? `Blocked by Crease: ${dns}.`.replace(/\.\.$/, ".") : null
}

function checkToolInner(root: string, toolName: string, input: Record<string, unknown>, opts: PolicyOptions): string | null {
  if (DISALLOWED.has(toolName)) return `Blocked by Crease: ${toolName} isn't available in a design session.`
  if (WRITE_TOOLS.has(toolName)) {
    const raw = (input.file_path ?? input.notebook_path ?? input.path) as string | undefined
    if (!raw) return "Missing file path."
    return protectedReason(root, String(raw))
  }
  if (toolName === "Bash") {
    if (input.dangerouslyDisableSandbox) return "Blocked by Crease: the shell always runs in the sandbox; drop dangerouslyDisableSandbox."
    const why = checkBash(root, String(input.command ?? ""), opts)
    return why ? `Blocked by Crease: ${why}.` : null
  }
  if (toolName === "WebFetch") {
    const why = checkFetchUrl(String(input.url ?? ""), opts)
    return why ? `Blocked by Crease: ${why}.` : null
  }
  if (READ_TOOLS.has(toolName)) {
    const paths = [input.file_path, input.notebook_path, input.path].filter((x): x is string => typeof x === "string" && x !== "")
    if (paths.some((p) => readDenied(root, p, opts)))
      return "Blocked by Crease: that is the app's private settings/key store. Work with files inside the project instead."
    if (opts.readRoots) {
      for (const p of paths) {
        const why = readOutsideReason(root, p, opts.readRoots)
        if (why) return why
      }
      if (toolName === "Glob" && typeof input.pattern === "string") {
        const why = readOutsideReason(root, input.pattern, opts.readRoots, { glob: true })
        if (why) return why
      }
    }
  }
  // The sandbox's network permission prompt: nobody is at a terminal, and the shell has no network by design.
  if (toolName === "SandboxNetworkAccess") return `Blocked by Crease: ${NET_MSG}.`
  return null
}

export interface PolicyHooks {
  /** Handles AskUserQuestion: show the questions to the user and resolve with their answers. */
  askUser?: (input: Record<string, unknown>, opts: { signal: AbortSignal; toolUseID?: string }) => Promise<PermissionResult>
}

/**
 * PreToolUse hook running checkTool for every tool call. Hooks run before permission rules, so a "deny" here
 * holds even when a settings file (or a future source) has an allow rule for the tool.
 */
export function policyHooks(root: string, opts: PolicyOptions = {}): Partial<Record<HookEvent, HookCallbackMatcher[]>> {
  return {
    PreToolUse: [
      {
        hooks: [
          async (input) => {
            if (input.hook_event_name !== "PreToolUse") return {}
            const why = await checkToolAsync(root, input.tool_name, (input.tool_input ?? {}) as Record<string, unknown>, opts)
            if (!why) return {}
            return { hookSpecificOutput: { hookEventName: "PreToolUse", permissionDecision: "deny", permissionDecisionReason: why } }
          },
        ],
      },
    ],
  }
}

export function makeCanUseTool(root: string, hooks: PolicyHooks = {}, opts: PolicyOptions = {}): CanUseTool {
  return async (toolName, input, o) => {
    if (toolName === "AskUserQuestion") {
      if (!hooks.askUser) return { behavior: "deny", message: "No one is available to answer questions; use sensible defaults." }
      return hooks.askUser(input, { signal: o.signal, toolUseID: o.toolUseID })
    }
    const why = await checkToolAsync(root, toolName, input, opts)
    if (why) return { behavior: "deny", message: why }
    // Everything else (Read/Glob/Grep, Task, TodoWrite, WebSearch, Skill, MCP tools...) is allowed.
    // There is no human at a terminal to ask; request_print does its own UI confirmation.
    return { behavior: "allow", updatedInput: input }
  }
}
