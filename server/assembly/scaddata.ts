// lib/studio_assembly_data.scad: generated from assembly.json (placements + motions) before every render,
// so assembly.scad, the guide renders, check_motion and the 3D viewer all use the same poses.
import type { Assembly, AssemblyMotion } from "../../shared/types"

export const SCADDATA_FILE = "lib/studio_assembly_data.scad"

const v3 = (v: readonly number[]) => `[${v.map((n) => +n.toFixed(6)).join(", ")}]`

/** Fraction (0..1 across range) for a motion value. */
export function motionFraction(m: AssemblyMotion, value: number): number {
  return (value - m.range[0]) / (m.range[1] - m.range[0])
}
export const restValue = (m: AssemblyMotion) => m.rest ?? m.range[0]

/**
 * Motions that move a part instance, in canonical order: assembly.motions order, applied first to last. A part that
 * moves with two motions (a lid hinged on a sliding drawer) is posed by the first, then the second carries the
 * result, so list the inner motion (the hinge) before the one that carries it (the drawer). Axes and origins are
 * in assembly coordinates at the placed pose. Used by check_motion, the 3D viewers and studio_assembly_data.scad.
 */
export function motionsFor(a: Assembly, part: string, instance: number): AssemblyMotion[] {
  return (a.motions ?? []).filter((m) => m.parts.some((r) => r === part || r === `${part}#${instance}`))
}

export function scadData(a: Assembly): string {
  const out: string[] = [
    "// studio_assembly_data.scad -- generated by Crease from assembly.json; do not edit",
    "// (rewritten before every render). Edit placements/motions in assembly.json instead.",
    "",
  ]
  for (const m of a.motions ?? []) {
    out.push(`motion_${m.id} = ${+motionFraction(m, restValue(m)).toFixed(6)}; // ${m.label}: 0..1 across ${m.range[0]}..${m.range[1]}${m.type === "rotate" ? "°" : " mm"}`)
  }
  out.push("", "// placed(id, i): part instance i in its assembled position (rest pose of every motion excluded).")
  out.push("module placed(id, i = 0) {")
  const branches: string[] = []
  for (const pl of a.placements ?? []) {
    const r = pl.rotate ?? [0, 0, 0]
    branches.push(`if (id == ${JSON.stringify(pl.part)} && i == ${pl.instance ?? 0}) translate(${v3(pl.translate)}) rotate(${v3(r)}) part(${JSON.stringify(pl.part)});`)
  }
  branches.push(`{ echo(str("WARNING: no placement for ", id, " #", i, " in assembly.json")); part(id); }`)
  out.push("  " + branches.join("\n  else "), "}", "")
  out.push("// moving(id) children: moves children with motion <id> to its current pose (motion_<id>).")
  out.push("module moving(id) {")
  const mb: string[] = []
  for (const m of a.motions ?? []) {
    const val = `(${m.range[0]} + motion_${m.id} * ${m.range[1] - m.range[0]})`
    const o = m.origin ?? [0, 0, 0]
    if (m.type === "rotate") mb.push(`if (id == ${JSON.stringify(m.id)}) translate(${v3(o)}) rotate(a = ${val}, v = ${v3(m.axis)}) translate(${v3(o.map((x) => -x))}) children();`)
    else mb.push(`if (id == ${JSON.stringify(m.id)}) translate(${val} * ${v3(m.axis)} / norm(${v3(m.axis)})) children();`)
  }
  mb.push("children();")
  out.push("  " + mb.join("\n  else "), "}", "")
  out.push("// at(id, i): the part instance placed and moved by every motion it belongs to (use this in assembly.scad).")
  out.push("module at(id, i = 0) {")
  const ab: string[] = []
  for (const p of a.parts) {
    for (let i = 0; i < p.qty; i++) {
      const ms = motionsFor(a, p.id, i)
      if (!ms.length) continue
      // Canonical order (same as check_motion and both viewers): motions apply in assembly.motions order, the first
      // listed first. OpenSCAD applies the innermost wrapper first, so the first motion is written last.
      const wrap = [...ms].reverse().map((m) => `moving(${JSON.stringify(m.id)})`).join(" ")
      ab.push(`if (id == ${JSON.stringify(p.id)} && i == ${i}) ${wrap} placed(id, i);`)
    }
  }
  ab.push("placed(id, i);")
  out.push("  " + ab.join("\n  else "), "}", "")
  return out.join("\n")
}
