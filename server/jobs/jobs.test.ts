import { afterAll, beforeAll, describe, expect, it } from "vitest"
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { createHash } from "node:crypto"

// config.ts reads PRINTSTUDIO_HOME at import time: point everything (machines, projects, catalog) at a temp folder,
// so the only printer these tests can reach is the in-process practice printer.
const home = mkdtempSync(join(tmpdir(), "printstudio-jobs-test-"))
process.env.PRINTSTUDIO_HOME = home
process.env.PRACTICE_PRINT_SECONDS = "1"

const machines = await import("../machines")
const store = await import("../projects/store")
const jobs = await import("./index")
const printer = await import("../printer/index")
const { stopPractice } = await import("../printer/practice")

const sha = (b: Buffer | string) => createHash("sha256").update(b).digest("hex")
let P = ""
let root = ""
let practiceId = ""

const gcode = (tag: string) =>
  [
    "; HEADER_BLOCK_START",
    "; generated by OrcaSlicer 2.4.2 on 2026-10-08 at 10:00:00",
    "; HEADER_BLOCK_END",
    "; printstudio_intent = standard",
    `; tag ${tag}`,
    "G28",
    "G1 X10 Y10 Z0.2 E1",
    "; estimated printing time (normal mode) = 1m 2s",
    "; total filament used [g] = 1.23",
    "; CONFIG_BLOCK_START",
    "; layer_height = 0.2",
    '; print_settings_id = "0.20mm Standard"',
    "; CONFIG_BLOCK_END",
    "",
  ].join("\n")

/** Write G-code as the slicer would and snapshot it as a job (what slicePart/slicePlate do after OrcaSlicer). */
async function sliceFake(rel: string, tag: string, opts: { kind?: "part" | "plate"; plate?: number; plateCount?: number } = {}) {
  const source = await jobs.sourceRevision(P, ["main"])
  writeFileSync(join(root, rel), gcode(tag))
  const m = machines.getMachine(practiceId)
  return jobs.createJob(P, join(root, rel), {
    kind: opts.kind ?? "part",
    parts: [{ partId: "main", qty: 1 }],
    allParts: opts.kind === "plate",
    plate: opts.plate,
    plateCount: opts.plateCount,
    machine: m,
    slicedFor: m,
    intent: "standard",
    source,
    estimates: { estimatedTimeS: 62, filamentG: 1.23, filamentMm: null },
  })
}

beforeAll(async () => {
  practiceId = machines.ensurePracticeMachine({ makeDefault: true }).id
  const p = await store.createProject("Jobs test")
  P = p.id
  root = store.projectDir(P)
  await store.updateProject(P, { printer: practiceId, intent: "standard" })
})
afterAll(async () => {
  await stopPractice()
  rmSync(home, { recursive: true, force: true })
})

describe("print jobs: immutable, content-addressed", () => {
  it("id is the sha256 of the exact bytes; the snapshot is a read-only copy; same bytes = same job", async () => {
    const job = await sliceFake("build/main.gcode", "a")
    const bytes = readFileSync(join(root, "build/main.gcode"))
    expect(job.id).toBe(sha(bytes))
    expect(job.snapshotPath).toBe(`.studio/jobs/${job.id}/main.gcode`)
    const snap = join(root, job.snapshotPath)
    expect(readFileSync(snap).equals(bytes)).toBe(true)
    expect(statSync(snap).mode & 0o222).toBe(0)
    expect(job).toMatchObject({ kind: "part", partIds: ["main"], machineId: practiceId, intent: "standard", bytes: bytes.length })
    expect(job.slicer).toMatchObject({ name: "OrcaSlicer", version: "2.4.2", printProfile: "0.20mm Standard" })
    expect(job.settings.layer_height).toBe("0.2")
    expect(job.source.parts.main).toMatch(/^[0-9a-f]{16}$/)
    expect(job.designRevision).toMatch(/^[0-9a-f]{16}$/)
    expect((await sliceFake("build/main.gcode", "a")).createdAt).toBe(job.createdAt)
    expect(jobs.getJobForGcode(P, "build/main.gcode")?.id).toBe(job.id)
    expect(jobs.readJobBytes(P, job).equals(bytes)).toBe(true)
  })

  it("refuses a snapshot that was modified after slicing", async () => {
    const job = await sliceFake("build/tamper.gcode", "tamper")
    const snap = join(root, job.snapshotPath)
    chmodSync(snap, 0o644)
    writeFileSync(snap, gcode("tamper") + "M104 S300\n")
    expect(() => jobs.readJobBytes(P, job)).toThrow(/modified after slicing/)
  })

  it("refuses to request G-code no slice made (hand-edited / copied in)", async () => {
    await sliceFake("build/main.gcode", "b")
    writeFileSync(join(root, "build/main.gcode"), gcode("b") + "; edited by hand\n")
    await expect(printer.createPrintRequest(P, "build/main.gcode", "user")).rejects.toMatchObject({ statusCode: 409 })
  })

  it("refuses when the bytes differ from the job the caller reviewed (agent request_print)", async () => {
    const job = await sliceFake("build/main.gcode", "c")
    await expect(printer.createPrintRequest(P, "build/main.gcode", "agent", undefined, "0".repeat(64))).rejects.toThrow(/changed after it was reviewed/)
    const { request } = await printer.createPrintRequest(P, "build/main.gcode", "agent", undefined, job.id)
    expect(request.job?.id).toBe(job.id)
    await printer.answerPrintRequest(request.requestId, false, false)
  })

  it("editing the G-code after the request makes the upload refuse (nothing is sent)", async () => {
    const job = await sliceFake("build/main.gcode", "d")
    jobs.recordPartJob(P, "main", job.id)
    const { request, outcome } = await printer.createPrintRequest(P, "build/main.gcode", "user")
    expect(request.job?.id).toBe(job.id)
    expect((await jobs.currentJob(P, "main"))?.status).toBe("requested")
    writeFileSync(join(root, "build/main.gcode"), gcode("d") + "; changed\n")
    await expect(printer.answerPrintRequest(request.requestId, true, true)).rejects.toMatchObject({ statusCode: 409 })
    expect(await outcome).toMatchObject({ approved: false })
    const v = await jobs.currentJob(P, "main")
    expect(v?.status).toBe("rejected")
    expect(v?.error).toMatch(/changed after this request/)
  })

  it("picking another machine in the dialog is refused (it needs its own job), request stays open", async () => {
    const other = machines.createMachine({ name: "Other printer", model: "Creality SPARKX i7", connection: { type: "none" } })
    const job = await sliceFake("build/main.gcode", "e")
    const { request } = await printer.createPrintRequest(P, "build/main.gcode", "user")
    await expect(printer.answerPrintRequest(request.requestId, true, true, other.id)).rejects.toThrow(/prepared for .*Slice again for Other printer/)
    expect(printer.listPrintRequests().some((r) => r.requestId === request.requestId)).toBe(true)
    await expect(printer.createPrintRequest(P, "build/main.gcode", "user", other.id)).rejects.toMatchObject({ statusCode: 409 })
    await printer.answerPrintRequest(request.requestId, false, false)
    expect(job.machineId).toBe(practiceId)
    machines.deleteMachine(other.id)
  })

  it("a job sliced for the machine a request names is current for that machine, not the project's default (E2E #2 P1-b)", async () => {
    const other = machines.createMachine({ name: "Other printer", model: "Creality SPARKX i7", connection: { type: "none" } })
    const source = await jobs.sourceRevision(P, ["main"])
    writeFileSync(join(root, "build/main.other.gcode"), gcode("for-other"))
    const job = await jobs.createJob(P, join(root, "build/main.other.gcode"), {
      kind: "part",
      parts: [{ partId: "main", qty: 1 }],
      machine: other,
      slicedFor: other,
      intent: "standard",
      source,
      estimates: { estimatedTimeS: 62, filamentG: 1.23, filamentMm: null },
    })
    expect(await jobs.staleReasons(P, job, other.id)).toEqual([])
    expect(await jobs.staleReasons(P, job)).toEqual(["the project now prints on Practice printer"])
    expect(await jobs.staleReasons(P, job, practiceId)).toEqual(["it was sliced for Other printer, not Practice printer"])
    const { request } = await printer.createPrintRequest(P, "build/main.other.gcode", "user", other.id)
    expect(request.machineId).toBe(other.id)
    await printer.answerPrintRequest(request.requestId, false, false)
    machines.deleteMachine(other.id)
  })
})

describe("staleness (server-owned)", () => {
  it("source edits, intent and machine changes make a job stale; undoing them makes it current again", async () => {
    const job = await sliceFake("build/main.gcode", "s")
    jobs.recordPartJob(P, "main", job.id)
    const stale = async () => (await jobs.currentJob(P, "main"))!.stale
    expect(await stale()).toEqual([])
    await expect(printer.createPrintRequest(P, "build/main.gcode", "user")).resolves.toBeTruthy()
    for (const r of printer.listPrintRequests()) await printer.answerPrintRequest(r.requestId, false, false)

    const scad = join(root, "parts/main.scad")
    const src = readFileSync(scad, "utf8")
    writeFileSync(scad, src.replace("width = 40", "width = 41"))
    expect(await stale()).toEqual(["main: parts/main.scad changed since it was sliced"])
    await expect(printer.createPrintRequest(P, "build/main.gcode", "user")).rejects.toThrow(/Out of date — slice again/)
    writeFileSync(scad, src)
    expect(await stale()).toEqual([])

    // assembly colours/placements are part of the design revision (what the agent's approval is keyed on) ...
    const asm = { parts: [{ id: "main", qty: 1, color: "red" }], hardware: [{ id: "s", type: "screw", qty: 2 }], tools: [], consumables: [], steps: [] }
    writeFileSync(join(root, "assembly.json"), JSON.stringify(asm)) // a shopping list only: not the design
    expect(await stale()).toEqual([])
    writeFileSync(join(root, "assembly.json"), JSON.stringify({ ...asm, placements: [{ part: "main", translate: [0, 0, 0] }] }))
    expect(await stale()).toEqual(["the design changed since it was sliced"])
    rmSync(join(root, "assembly.json"))
    // ... a .scad file no part uses (a scratch file, the guide's assembly.scad) is not
    writeFileSync(join(root, "lib/extra.scad"), "module x() {}")
    expect(await stale()).toEqual([])
    rmSync(join(root, "lib/extra.scad"))

    await jobs.setProjectIntent(P, "display")
    expect(await stale()).toEqual(["print settings changed to display"])
    await jobs.setProjectIntent(P, "standard")

    const other = machines.createMachine({ name: "Second", model: "Creality SPARKX i7", connection: { type: "none" } })
    await store.updateProject(P, { printer: other.id })
    expect(await stale()).toEqual(["the project now prints on Second"])
    await store.updateProject(P, { printer: practiceId })
    machines.deleteMachine(other.id)
    expect(await stale()).toEqual([])
  })

  it("a plate of every part goes stale when a part is added", async () => {
    const job = await sliceFake("build/plate.gcode", "plate-x", { kind: "plate", plate: 1, plateCount: 1 })
    jobs.recordPlateSet(P, [job.id])
    writeFileSync(join(root, "parts/lid.scad"), "cube(5);")
    expect((await jobs.projectJobs(P)).plates?.stale).toContain("lid was added to the project")
    rmSync(join(root, "parts/lid.scad"))
    await store.getProject(P)
    expect((await jobs.projectJobs(P)).plates?.stale).toEqual([])
  })
})

describe("plate lifecycle", () => {
  it("cursor stays on a rejected/failed plate, advances only on a recorded start, survives reload", async () => {
    const a = await sliceFake("build/plate-1.gcode", "p1", { kind: "plate", plate: 1, plateCount: 2 })
    const b = await sliceFake("build/plate-2.gcode", "p2", { kind: "plate", plate: 2, plateCount: 2 })
    jobs.recordPlateSet(P, [a.id, b.id])
    const plates = async () => (await jobs.projectJobs(P)).plates!
    expect((await plates()).next).toBe(0)

    // request + reject plate 1: cursor stays on it
    let req = (await printer.createPrintRequest(P, "build/plate-1.gcode", "user")).request
    expect((await plates()).plates[0].status).toBe("requested")
    expect((await plates()).next).toBe(0)
    await printer.answerPrintRequest(req.requestId, false, false)
    // "Don't print" never sent anything: the plate is simply still to print
    expect((await plates()).plates.map((p) => p.status)).toEqual(["pending", "pending"])
    expect((await plates()).next).toBe(0)

    // approve plate 1 on the practice printer: printing, cursor moves to plate 2
    expect(machines.getMachine(practiceId).isPractice).toBe(true)
    req = (await printer.createPrintRequest(P, "build/plate-1.gcode", "user")).request
    expect(req.machineId).toBe(practiceId)
    const r = await printer.answerPrintRequest(req.requestId, true, true)
    expect(r.ok).toBe(true)
    let ps = await plates()
    expect(ps.plates[0].status).toBe("printing")
    expect(ps.plates[0].printId).toBeTruthy()
    expect(ps.next).toBe(1)

    // the print failed: plate 1 is back for a retry
    jobs.notePrintFinished(P, ps.plates[0].printId!, "cancelled")
    ps = await plates()
    expect(ps.plates[0].status).toBe("failed")
    expect(ps.next).toBe(0)

    // persisted on disk (a reloaded UI / restarted server reads the same state)
    const onDisk = JSON.parse(readFileSync(join(root, ".studio/jobs/state.json"), "utf8"))
    expect(onDisk.plateSet.jobIds).toEqual([a.id, b.id])
    expect(onDisk.jobs[a.id].status).toBe("failed")

    // a request whose dialog no longer exists (server restarted) counts as pending again
    jobs.setJobStatus(P, b.id, "requested", { requestId: "gone" })
    expect((await plates()).plates[1].status).toBe("pending")

    // completing marks it done
    jobs.setJobStatus(P, a.id, "printing", { printId: "print-1" })
    jobs.notePrintFinished(P, "print-1", "complete")
    expect((await plates()).plates[0].status).toBe("done")
    expect((await plates()).next).toBe(1)

  })

  it("placement of an older job (no recorded objects) is read from its G-code snapshot", async () => {
    const head = readFileSync(join(import.meta.dirname, "../slicer/fixtures/plate-perpart.head.gcode"), "utf8")
    writeFileSync(join(root, "build/plate.gcode"), head + "\n; printable_area = 0x0,260x0,260x260,0x260\n")
    const m = machines.getMachine(practiceId)
    const job = await jobs.createJob(P, join(root, "build/plate.gcode"), {
      kind: "plate",
      parts: [{ partId: "tag-a", qty: 2 }, { partId: "tag-b", qty: 1 }],
      plate: 1,
      plateCount: 1,
      machine: m,
      slicedFor: m,
      intent: "standard",
      source: await jobs.sourceRevision(P, ["main"]),
      estimates: { estimatedTimeS: null, filamentG: null, filamentMm: null },
    })
    const pl = jobs.jobPlacement(P, job.id)!
    expect(pl).toMatchObject({ kind: "plate", plate: 1, bedMm: [260, 260], front: "-y", source: "gcode" })
    expect(pl.objects.map((o) => `${o.label}:${o.partId}#${o.instance}`)).toEqual(["A:tag-a#1", "B:tag-a#2", "C:tag-b#1"])
    // no mesh in build/ for these parts: positions only (the UI draws the footprint)
    expect(pl.objects[0].rotationDeg).toBeNull()
    expect(pl.objects[0].polygon.length).toBeGreaterThan(2)
    expect(jobs.jobPlacement(P, "0".repeat(64))).toBeNull()
  })
})

