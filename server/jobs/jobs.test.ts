describe("E2E fixes: re-slice inputs, Customizer staleness, restart", () => {
  it("a Customizer value change makes the latest slice stale (and back)", async () => {
    const revision = await import("../projects/revision")
    const job = await sliceFake("build/main.gcode", "cz")
    jobs.recordPartJob(P, "main", job.id)
    expect((await jobs.currentJob(P, "main"))!.stale).toEqual([])
    expect(revision.savePartOverrides(root, "main", { width: 22 })).toBe(true)
    expect((await jobs.currentJob(P, "main"))!.stale.join(" ")).toMatch(/Customizer values changed \(width\)/)
    await expect(printer.createPrintRequest(P, "build/main.gcode", "user")).rejects.toThrow(/Out of date — slice again/)
    expect(revision.savePartOverrides(root, "main", { width: 22 })).toBe(false) // same values: no change
    expect(revision.savePartOverrides(root, "main", {})).toBe(true)
    expect((await jobs.currentJob(P, "main"))!.stale).toEqual([])
  })

  it("latestSliceInputs: the latest plate's composition, per-part and process overrides (not automatic ones)", async () => {
    const source = await jobs.sourceRevision(P, ["main"])
    writeFileSync(join(root, "build/plate.gcode"), gcode("reuse-plate"))
    const m = machines.getMachine(practiceId)
    const pj = await jobs.createJob(P, join(root, "build/plate.gcode"), {
      kind: "plate",
      parts: [{ partId: "main", qty: 2, overrides: { wall_loops: 4 } }],
      allParts: false,
      plate: 1,
      plateCount: 1,
      machine: m,
      slicedFor: m,
      intent: "display",
      overrides: { sparse_infill_density: "25%", top_surface_pattern: "concentric", ironing_pattern: "concentric" },
      userOverrides: { sparse_infill_density: "25%" },
      source,
      estimates: { estimatedTimeS: 62, filamentG: 1.23, filamentMm: null },
    })
    expect(pj.userOverrides).toEqual({ sparse_infill_density: "25%" })
    jobs.recordPlateSet(P, [pj.id])
    expect(await jobs.latestSliceInputs(P)).toEqual({
      intent: "display",
      overrides: { sparse_infill_density: "25%" },
      parts: [{ partId: "main", qty: 2, overrides: { wall_loops: 4 } }],
      jobId: pj.id,
    })
    // a single-part re-slice folds that part's per-part settings into its own (the plate is newer than its part job)
    const forPart = await jobs.latestSliceInputs(P, "main")
    expect(forPart).toMatchObject({ intent: "display", overrides: { sparse_infill_density: "25%", wall_loops: 4 }, jobId: pj.id })
  })

  it("a print request lost to a restart goes back to pending with a notice", async () => {
    const job = await sliceFake("build/main.gcode", "restart")
    jobs.recordPartJob(P, "main", job.id)
    jobs.setJobStatus(P, job.id, "requested", { requestId: "lost-in-restart" })
    expect(jobs.recoverInterruptedRequests()).toEqual([P])
    const v = (await jobs.currentJob(P, "main"))!
    expect(v.status).toBe("pending")
    expect(v.requestId).toBeNull()
    const { PRINT_REQUEST_RESTART_NOTICE } = await import("../../shared/types")
    expect(v.error).toBe(PRINT_REQUEST_RESTART_NOTICE)
    expect(jobs.recoverInterruptedRequests()).toEqual([]) // once
  })
})
