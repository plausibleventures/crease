import { afterAll, beforeAll, describe, expect, it } from "vitest"
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

// Temp home: the only printer these tests can reach is the in-process practice printer (prints are simulated).
const home = mkdtempSync(join(tmpdir(), "printstudio-outcomes-test-"))
process.env.PRINTSTUDIO_HOME = home
process.env.PRACTICE_PRINT_SECONDS = "1"

const machines = await import("../machines")
const store = await import("../projects/store")
const jobs = await import("../jobs")
const db = await import("../db")
const printer = await import("../printer/index")
const outcomes = await import("./index")
const lessons = await import("../agent/lessons")
const { stopPractice } = await import("../printer/practice")

let P = ""
let root = ""
let practiceId = ""

const gcode = (tag: string) =>
  ["; generated by OrcaSlicer 2.4.2", "; printstudio_intent = display", `; tag ${tag}`, "G28", "G1 X10 Y10 Z0.2 E1", "; CONFIG_BLOCK_START", "; layer_height = 0.2", "; CONFIG_BLOCK_END", ""].join("\n")

async function slicePlate(rel: string, tag: string, plate: number, plateCount: number) {
  const source = await jobs.sourceRevision(P, ["main"])
  writeFileSync(join(root, rel), gcode(tag))
  const m = machines.getMachine(practiceId)
  return jobs.createJob(P, join(root, rel), {
    kind: "plate",
    parts: [{ partId: "main", qty: 1 }],
    allParts: true,
    plate,
    plateCount,
    machine: m,
    slicedFor: m,
    intent: "display",
    source,
    estimates: { estimatedTimeS: 35 * 60, filamentG: 4, filamentMm: null },
  })
}

/** Approve a plate on the practice printer, then simulate the printer reporting the end after `minutes`. */
async function printAndFinish(rel: string, minutes: number, state: "complete" | "cancelled" = "complete") {
  const { request } = await printer.createPrintRequest(P, rel, "user")
  expect((await printer.answerPrintRequest(request.requestId, true, true)).ok).toBe(true)
  const view = await jobs.jobView(P, request.job!.id)
  const printId = view!.printId!
  const rec = db.getPrint(printId)!
  const end = new Date(Date.parse(rec.startedAt) + minutes * 60_000).toISOString()
  db.recordPrintFinish(printId, state, end)
  jobs.notePrintFinished(P, printId, state)
  return printId
}

beforeAll(async () => {
  practiceId = machines.ensurePracticeMachine({ makeDefault: true }).id
  const p = await store.createProject("Outcomes test")
  P = p.id
  root = store.projectDir(P)
  await store.updateProject(P, { printer: practiceId, intent: "display" })
})
afterAll(async () => {
  await stopPractice()
  rmSync(home, { recursive: true, force: true })
})

describe("print outcomes", () => {
  let printId = ""
  let jobId = ""

  it("a finished print knows its job, scope and real duration; the outcome attaches to job + catalog", async () => {
    const a = await slicePlate("build/plate-1.gcode", "o1", 1, 2)
    const b = await slicePlate("build/plate-2.gcode", "o2", 2, 2)
    jobs.recordPlateSet(P, [a.id, b.id])
    jobId = a.id
    printId = await printAndFinish("build/plate-1.gcode", 42)
    const rec = db.getPrint(printId)!
    expect(rec).toMatchObject({ jobId: a.id, state: "complete", actualDurationS: 42 * 60, estimatedTimeS: 35 * 60 })
    expect(rec.scope).toMatchObject({ machineId: practiceId, intent: "display", material: "PLA" })
    expect((await jobs.projectJobs(P)).plates!.next).toBe(1)

    const photo = outcomes.addPhoto(printId, Buffer.from([0xff, 0xd8, 0xff, 0xe0, 1, 2, 3]), "image/jpeg")
    expect(photo.url).toBe(`/api/prints/${printId}/photos/${photo.name}`)
    expect(existsSync(join(root, ".studio/jobs", a.id, "photos", photo.name))).toBe(true)
    expect(() => outcomes.addPhoto(printId, Buffer.from("x"), "application/pdf")).toThrow(/JPEG, PNG or WebP/)

    const saved = outcomes.saveOutcome(printId, {
      rating: "problem",
      categories: ["wrong_size"],
      notes: "Lid is hard to push on.",
      photos: [photo.name, "../../etc-passwd.jpg"],
      measurements: [{ name: "Pen hole", kind: "hole", expectedMm: 10, measuredMm: 9.76, partId: "main" }],
      fits: [{ name: "Lid on box", result: "too_tight", clearanceMm: 0.15 }],
    })
    expect(saved.result).toBe("success") // mirrors for older readers
    expect(saved.notes).toBe("Lid is hard to push on.")
    expect(saved.outcome).toMatchObject({ rating: "problem", jobId: a.id, photos: [photo.name], actualDurationS: 2520 })
    expect(saved.outcome!.lesson).toMatchObject({ status: "proposed", machineId: practiceId })
    expect(saved.outcome!.lesson!.text).toMatch(/Holes print about 0.24 mm small/)

    // immutable job gets outcome.json; catalog row and .studio/prints/<id>.json carry it too
    const onJob = JSON.parse(readFileSync(join(root, ".studio/jobs", a.id, "outcome.json"), "utf8"))
    expect(onJob.jobId).toBe(a.id)
    expect(onJob.outcomes).toHaveLength(1)
    expect(onJob.outcomes[0].measurements[0].measuredMm).toBe(9.76)
    expect(JSON.parse(readFileSync(join(root, ".studio/prints", `${printId}.json`), "utf8")).outcome.rating).toBe("problem")
    db.rebuildIndex()
    expect(db.getPrint(printId)!.outcome!.fits[0].result).toBe("too_tight")
    expect(outcomes.projectOutcomes(P).map((o) => o.printId)).toEqual([printId])
  })

  it("marking a completed plate failed sends it back to the cursor for a retry", async () => {
    outcomes.saveOutcome(printId, { rating: "failed", categories: ["didnt_stick"] })
    const ps = (await jobs.projectJobs(P)).plates!
    expect(ps.plates[0].status).toBe("failed")
    expect(ps.next).toBe(0)
    expect(db.getPrint(printId)!.result).toBe("failed")
  })

  it("lessons: accept (edited) writes lessons.md, undo removes exactly that line, dismiss sticks", () => {
    const edited = "Holes print 0.25 mm small in PLA; add 0.25 mm to holes"
    const acc = outcomes.decideLesson(printId, "accept", edited)
    expect(acc.outcome!.lesson).toMatchObject({ status: "accepted", text: edited })
    expect(acc.outcome!.lesson!.line).toMatch(/^- \d{4}-\d{2}-\d{2}: Holes print 0.25 mm small/)
    expect(lessons.listLessons(practiceId).map((l) => l.text)).toEqual([expect.stringContaining(edited)])
    // saving the outcome again keeps the decision
    expect(outcomes.saveOutcome(printId, { rating: "failed", categories: ["didnt_stick"] }).outcome!.lesson!.status).toBe("accepted")
    expect(() => outcomes.decideLesson(printId, "dismiss")).toThrow(/undo/)

    lessons.addLesson(practiceId, "Practice", "Another lesson the user typed", "chat")
    const undone = outcomes.decideLesson(printId, "undo")
    expect(undone.outcome!.lesson).toMatchObject({ status: "undone", line: null })
    expect(lessons.listLessons(practiceId).map((l) => l.text)).toEqual([expect.stringContaining("Another lesson")])
    expect(outcomes.decideLesson(printId, "dismiss").outcome!.lesson!.status).toBe("dismissed")

    // accepted later, then removed from Settings → Machines: the outcome reads as undone
    const line = outcomes.decideLesson(printId, "accept").outcome!.lesson!.line!
    expect(outcomes.forgetLesson(practiceId, line)).toBe(true)
    expect(db.getPrint(printId)!.outcome!.lesson).toMatchObject({ status: "undone", line: null })
    expect(lessons.listLessons(practiceId)).toHaveLength(1)
  })

  it("calibration: time factor from real prints adjusts shown estimates; fit suggestions", async () => {
    const report = outcomes.calibrationReport({ machineId: practiceId, intent: "display" })
    expect(report.time).toMatchObject({ factor: 1.2, prints: 1, scope: "exact" })
    expect(report.tolerances.map((t) => t.key).sort()).toEqual(["holeCompensationMm", "slidingFitMm"])
    const view = (await jobs.projectJobs(P)).plates!.plates[1]
    expect(view.adjustedTime).toEqual({ estimatedTimeS: 42 * 60, rawEstimateS: 35 * 60, factor: 1.2, prints: 1, scope: "exact" })
  })

  it("jobs with outcomes are never pruned", async () => {
    const plate2 = (await jobs.projectJobs(P)).plates!.plates[1].id
    for (let i = 0; i < 24; i++) await slicePlate(`build/x${i}.gcode`, `x${i}`, 1, 1)
    jobs.recordPlateSet(P, [(await slicePlate("build/last.gcode", "last", 1, 1)).id]) // prunes beyond the newest 20
    expect(existsSync(join(root, ".studio/jobs", plate2))).toBe(false) // older, no outcome: pruned
    expect(existsSync(join(root, ".studio/jobs", jobId, "outcome.json"))).toBe(true)
  })
})
