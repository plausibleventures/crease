// R07: dependency-based artifact validity. Shared lib files, Customizer overrides and assembly data make dependent
// checks, renders, the guide, motion checks and print jobs stale even when a part's own file is untouched; restoring
// the old files makes them current again.
import { afterAll, beforeAll, describe, expect, it } from "vitest"
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import type { MotionCheck } from "../../shared/types"

// config.ts reads PRINTSTUDIO_HOME at import time: everything (machines, projects) lives in a temp folder, and the
// only printer reachable is the in-process practice printer.
const home = mkdtempSync(join(tmpdir(), "printstudio-validity-test-"))
process.env.PRINTSTUDIO_HOME = home

const machines = await import("../machines")
const store = await import("./store")
const revision = await import("./revision")
const validity = await import("./validity")
const jobs = await import("../jobs/index")
const { doneChecklist, guideRequired } = await import("../agent/done")
const { stopPractice } = await import("../printer/practice")

const okMotion = (): MotionCheck => ({ ok: true, status: "ok", incomplete: [], restCollisions: [], motions: [], combined: [], scope: { parts: [], hardware: [], skipped: [] }, notChecked: [], warnings: [], summary: "OK" })
const OPENSCAD = "/Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD"
let P = ""
let root = ""
let practiceId = ""
const write = (rel: string, content: string) => {
  mkdirSync(join(root, rel, ".."), { recursive: true })
  writeFileSync(join(root, rel), content)
}

/** What checkPart / buildAssemblyGuide / check_motion / the slicer record, without running OpenSCAD or OrcaSlicer. */
async function buildEverything() {
  const project = await store.getProject(P)
  for (const p of project.parts) {
    const source = revision.currentPartStampAt(root, p)
    write(`.studio/checks/${p.id}.json`, JSON.stringify({ partId: p.id, createdAt: new Date().toISOString(), items: [], summary: "pass", source }))
  }
  const asm = revision.assemblyStampAt(root, project.parts)
  write("build/assembly-guide.html", "<html/>")
  validity.writeGuideStamp(root, asm)
  validity.writeMotionRecord(root, asm, okMotion())
  const source = await jobs.sourceRevision(P, ["main"])
  write("build/main.gcode", `; generated by OrcaSlicer 2.4.2\n; tag ${Math.random()}\nG28\n`)
  const m = machines.getMachine(practiceId)
  const job = await jobs.createJob(P, join(root, "build/main.gcode"), {
    kind: "part",
    parts: [{ partId: "main", qty: 1 }],
    machine: m,
    slicedFor: m,
    intent: "standard",
    source,
    estimates: { estimatedTimeS: 60, filamentG: 1, filamentMm: null },
  })
  jobs.recordPartJob(P, "main", job.id)
}

const motion = (id: string) => ({ id, label: id, type: "rotate", parts: ["lid"], axis: [1, 0, 0], range: [0, 90] })
const asmJson = (...motions: string[]) => JSON.stringify({ parts: [{ id: "main", qty: 1, color: "white" }, { id: "lid", qty: 1, color: "white" }], hardware: [], tools: [], consumables: [], steps: [{ n: 1, title: "Put the lid on", text: "Press it down.", adds: ["lid"] }], motions: motions.map(motion) })

const states = async () => {
  const v = await validity.projectValidity(P)
  return {
    main: v.parts.main.check,
    lid: v.parts.lid.check,
    guide: v.assembly!.guide,
    motion: v.assembly!.motion!,
    job: (await jobs.currentJob(P, "main"))!.stale,
  }
}

beforeAll(async () => {
  practiceId = machines.ensurePracticeMachine({ makeDefault: true }).id
  const p = await store.createProject("Validity test")
  P = p.id
  root = store.projectDir(P)
  await store.updateProject(P, { printer: practiceId, intent: "standard" })
  write("lib/params.scad", "wall = 2;\n")
  write("parts/main.scad", "include <../lib/params.scad>\nwidth = 40;\ncube([width, 20, wall]);\n")
  write("parts/lid.scad", "include <../lib/params.scad>\nlid_w = 40;\ncube([lid_w, 20, wall]);\n")
  write("assembly.json", asmJson("open"))
  await store.getProject(P) // registers parts/lid.scad
  await store.saveCheckpoint(P, "user: base")
})
afterAll(async () => {
  await stopPractice()
  rmSync(home, { recursive: true, force: true })
})

describe("artifact validity (R07)", () => {
  it("everything built from the current files is fresh", async () => {
    await buildEverything()
    const s = await states()
    expect([s.main.state, s.lid.state, s.guide.state, s.motion.state]).toEqual(["fresh", "fresh", "fresh", "fresh"])
    expect(s.job).toEqual([])
    expect(await guideRequired(P)).toBeNull()
  })

  it("changing only lib/params.scad makes part checks, guide, motion and the job stale, with the reason", async () => {
    write("lib/params.scad", "wall = 3;\n") // the parts' own files are untouched
    const s = await states()
    for (const v of [s.main, s.lid, s.guide, s.motion]) {
      expect(v.state).toBe("stale")
      expect(v.reasons).toContain("lib/params.scad changed")
    }
    expect(s.job).toContain("main: lib/params.scad changed since it was sliced")
    // the Moves panel reads the same freshness through AssemblyInfo.motionCheck
    const asmMod = await import("../assembly/index")
    const mc = await asmMod.readMotionCheck(P, (await asmMod.readAssembly(P)).assembly)
    expect(mc).toMatchObject({ stale: true, staleReasons: ["lib/params.scad changed"] })
    const items = await doneChecklist(P)
    expect(items).toContain("main hasn't been checked since its last change: lib/params.scad changed (check_part)")
    expect(items.some((i) => /check_motion hasn't run since the last change: lib\/params.scad changed/.test(i))).toBe(true)
    expect(items.some((i) => /guide.*out of date: lib\/params.scad changed/.test(i))).toBe(true)
  })

  it("restoring the old tree makes the previously-fresh artifacts fresh again", async () => {
    const cp = (await store.listCheckpoints(P)).checkpoints.find((c) => c.message === "base")!
    await store.restoreCheckpoint(P, cp.commit)
    const s = await states()
    expect([s.main.state, s.lid.state, s.guide.state, s.motion.state]).toEqual(["fresh", "fresh", "fresh", "fresh"])
    expect(s.job).toEqual([])
  })

  it("changing a part's Customizer override makes that part stale only (and the assembly built from it)", async () => {
    // the Customizer re-renders lid with an override: its render record now carries the values
    const lid = (await store.getProject(P)).parts.find((p) => p.id === "lid")!
    const withOverride = revision.partStampAt(join(root, lid.file), { lid_w: 50 }, root)
    write("build/lid.render.json", JSON.stringify({ hash: withOverride.hash, files: withOverride.files, params: { lid_w: 50 } }))
    const v = await validity.projectValidity(P)
    expect(v.parts.lid.render.state).toBe("fresh")
    expect(v.parts.lid.overrides).toEqual({ lid_w: 50 })
    expect(v.parts.lid.check).toMatchObject({ state: "stale", reasons: ["Customizer values changed (lid_w)"] })
    expect(v.parts.main.check.state).toBe("fresh")
    expect((await jobs.currentJob(P, "main"))!.stale).toEqual([])
    expect(v.assembly!.guide.reasons).toEqual(["lid's Customizer values changed (lid_w)"])
    rmSync(join(root, "build/lid.render.json"))
    expect((await validity.projectValidity(P)).parts.lid.check.state).toBe("fresh")
  })

  it("assembly.json edits make the guide and motion check stale but not part checks", async () => {
    write("assembly.json", asmJson("open", "slide"))
    const s = await states()
    expect(s.guide.reasons).toEqual(["assembly.json changed"])
    expect(s.motion.reasons).toEqual(["assembly.json changed"])
    expect([s.main.state, s.lid.state]).toEqual(["fresh", "fresh"])
  })

  it("reports check reports from before stamps as out of date, and missing ones as missing", async () => {
    write(".studio/checks/main.json", JSON.stringify({ partId: "main", createdAt: new Date().toISOString(), items: [], summary: "pass" }))
    rmSync(join(root, ".studio/checks/lid.json"))
    const v = await validity.projectValidity(P)
    expect(v.parts.main.check.state).toBe("stale")
    expect(v.parts.lid.check.state).toBe("missing")
  })
})

describe.skipIf(!existsSync(OPENSCAD))("real render + check record their sources", () => {
  it("checkPart records the stamp; a lib edit makes it stale; re-checking makes it fresh", async () => {
    const cad = await import("../cad/index")
    write("lib/params.scad", "wall = 2;\n")
    await cad.checkPart(P, "main")
    expect((await validity.projectValidity(P)).parts.main.check.state).toBe("fresh")
    expect((await validity.projectValidity(P)).parts.main.render.state).toBe("fresh")
    write("lib/params.scad", "wall = 4;\n")
    const v = await validity.projectValidity(P)
    expect(v.parts.main.check.reasons).toEqual(["lib/params.scad changed"])
    expect(v.parts.main.render.reasons).toEqual(["lib/params.scad changed"])
    await cad.checkPart(P, "main") // exports a fresh STL first
    const after = await validity.projectValidity(P)
    expect([after.parts.main.check.state, after.parts.main.render.state]).toEqual(["fresh", "fresh"])
  }, 60_000)
})
