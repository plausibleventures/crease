// U1 print flow: a blank design is never sliced or printed; the print dialog's Print approves an unapproved design
// (user prints only); "Don't print" counts as never sent; slice errors stay on the overview in plain words; practice
// prints aren't rated; a template's declared colour picks the matching slot. Practice printer only: nothing real.
import { existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import Fastify, { type FastifyInstance } from "fastify"
import { afterAll, beforeAll, describe, expect, it } from "vitest"

// PRINTSTUDIO_HOME before any server import: only the in-process practice printer exists here.
const home = mkdtempSync(join(tmpdir(), "ps-print-flow-"))
process.env.PRINTSTUDIO_HOME = home
process.env.PRACTICE_PRINT_SECONDS = "1"

const ORCA = "/Applications/OrcaSlicer.app/Contents/MacOS/OrcaSlicer"
const OPENSCAD = "/Applications/OpenSCAD.app/Contents/MacOS/OpenSCAD"

const machines = await import("../machines")
const store = await import("../projects/store")
const jobs = await import("../jobs/index")
const printer = await import("../printer/index")
const approval = await import("../agent/approval")
const { projectOverview } = await import("../projects/overview")
const { recordSliceError, currentSliceError } = await import("../slicer/last-error")
const { plainSliceError } = await import("../../shared/slice-errors")
const { unratedPrints } = await import("../sync")
const { stopPractice } = await import("../printer/practice")

let app: FastifyInstance
let practiceId = ""

const gcode = (tag: string) =>
  [
    "; HEADER_BLOCK_START",
    "; generated by OrcaSlicer 2.4.2 on 2026-10-09 at 10:00:00",
    "; HEADER_BLOCK_END",
    "; printstudio_intent = standard",
    `; tag ${tag}`,
    "G28",
    "G1 X10 Y10 Z0.2 E1",
    "; estimated printing time (normal mode) = 1m 2s",
    "; total filament used [g] = 1.23",
    "; CONFIG_BLOCK_START",
    "; layer_height = 0.2",
    "; CONFIG_BLOCK_END",
    "",
  ].join("\n")

/** A slice of the project's main part as the slicer would leave it (G-code + job), without running OrcaSlicer. */
async function sliceFake(projectId: string, tag: string) {
  const root = store.projectDir(projectId)
  const source = await jobs.sourceRevision(projectId, ["main"])
  writeFileSync(join(root, "build/main.gcode"), gcode(tag))
  const m = machines.getMachine(practiceId)
  const job = await jobs.createJob(projectId, join(root, "build/main.gcode"), {
    kind: "part",
    parts: [{ partId: "main", qty: 1 }],
    machine: m,
    slicedFor: m,
    intent: "standard",
    source,
    estimates: { estimatedTimeS: 62, filamentG: 1.23, filamentMm: null },
  })
  jobs.recordPartJob(projectId, "main", job.id)
  return job
}

async function designedProject(name: string) {
  const p = await store.createProject(name)
  await store.updateProject(p.id, { printer: practiceId, intent: "standard" })
  writeFileSync(join(store.projectDir(p.id), "parts/main.scad"), "cube([20, 20, 10]);\n")
  return p.id
}

beforeAll(async () => {
  practiceId = machines.ensurePracticeMachine({ makeDefault: true }).id
  for (const m of machines.getMachines()) if (m.id !== practiceId) machines.deleteMachine(m.id)
  app = Fastify()
  app.setErrorHandler((err: Error & { statusCode?: number }, _req, reply) => reply.status(err.statusCode ?? 500).send({ error: err.message }))
  await app.register((await import("./printer")).default)
  printer.stopPrinterPolling()
})
afterAll(async () => {
  printer.stopPrinterPolling()
  await app?.close()
  await stopPractice()
  rmSync(home, { recursive: true, force: true })
})

describe("a blank design is never sliced or printed", () => {
  it("the slice, plate and print routes refuse the untouched starter part", async () => {
    const p = await store.createProject("Blank")
    expect(store.blankDesignAt(store.projectDir(p.id))).toBe(true)
    for (const [url, payload] of [
      [`/api/projects/${p.id}/parts/main/slice`, {}],
      [`/api/projects/${p.id}/slice-plate`, {}],
      [`/api/projects/${p.id}/print-requests`, { gcodePath: "build/main.gcode" }],
    ] as const) {
      const r = await app.inject({ method: "POST", url, payload })
      expect(r.statusCode, url).toBe(409)
      expect(r.json().error).toMatch(/Nothing is designed yet/)
    }
    // the designer's tools are refused too
    expect(approval.blankDesignGate(p.id)).toMatch(/nothing is designed yet/)
    writeFileSync(join(store.projectDir(p.id), "parts/main.scad"), "cube(10);\n")
    expect(store.blankDesignAt(store.projectDir(p.id))).toBe(false)
    expect(approval.blankDesignGate(p.id)).toBeNull()
  })
})

describe("approval folds into the print dialog's Print", () => {
  it("an unapproved design: the request says so, a plain OK is refused, Print with approveDesign approves this version and prints", async () => {
    const id = await designedProject("Fold approval")
    approval.setApproved(id, false)
    const job = await sliceFake(id, "a")
    const created = await app.inject({ method: "POST", url: `/api/projects/${id}/print-requests`, payload: { gcodePath: "build/main.gcode" } })
    expect(created.statusCode).toBe(200)
    const req = created.json()
    expect(req.needsApproval).toBe(true)
    expect(req.origin).toBe("user")

    const plain = await app.inject({ method: "POST", url: `/api/print-requests/${req.requestId}`, payload: { approved: true, bedClear: true } })
    expect(plain.statusCode).toBe(409)
    expect(plain.json().error).toMatch(/Approve the design first/)
    expect(printer.listPrintRequests().some((r) => r.requestId === req.requestId)).toBe(true) // still open
    expect(approval.isApproved(id)).toBe(false)

    const ok = await app.inject({ method: "POST", url: `/api/print-requests/${req.requestId}`, payload: { approved: true, bedClear: true, approveDesign: true } })
    expect(ok.statusCode).toBe(200)
    expect(ok.json()).toMatchObject({ ok: true, machineId: practiceId })
    expect(approval.isApproved(id)).toBe(true)
    expect((await jobs.currentJob(id, "main"))?.status).toBe("printing")
    expect((await jobs.jobView(id, job.id))?.status).toBe("printing")
  })

  it("an approved design prints without asking again; the designer's requests never carry the approval", async () => {
    const id = await designedProject("Already approved")
    approval.setApproved(id, true)
    await sliceFake(id, "b")
    const { request } = await printer.createPrintRequest(id, "build/main.gcode", "user")
    expect(request.needsApproval).toBe(false)
    await printer.answerPrintRequest(request.requestId, false, false)

    approval.setApproved(id, false)
    const agent = (await printer.createPrintRequest(id, "build/main.gcode", "agent")).request
    expect(agent.needsApproval).toBe(false)
    // answering the designer's request with approveDesign doesn't approve on its behalf
    await printer.answerPrintRequest(agent.requestId, false, false, undefined, { approveDesign: true })
    expect(approval.isApproved(id)).toBe(false)
  })
})

describe('"Don\'t print" is never sent', () => {
  it("the job goes back to pending with no error; the overview says Print it, not 'the last try didn't finish'", async () => {
    const id = await designedProject("Dont print")
    await sliceFake(id, "c")
    const { request, outcome } = await printer.createPrintRequest(id, "build/main.gcode", "user")
    const r = await app.inject({ method: "POST", url: `/api/print-requests/${request.requestId}`, payload: { approved: false, bedClear: false } })
    expect(r.statusCode).toBe(200)
    expect(await outcome).toMatchObject({ approved: false })
    const v = await jobs.currentJob(id, "main")
    expect(v).toMatchObject({ status: "pending", error: null })
    const o = await projectOverview(id)
    expect(o.plates[0].status).toBe("pending")
    if (o.next.kind === "print") expect(o.next).toMatchObject({ label: "Print it", detail: "You'll check the bed is clear first." })
    expect(o.next.detail).not.toMatch(/didn't finish/)
  })
})

describe("slice errors stay on the overview in plain words", () => {
  it("translates common OrcaSlicer errors", () => {
    expect(plainSliceError("OrcaSlicer failed (exit 206): plate 1: Nothing to be sliced, Either the print is empty or no object is fully inside the print volume before apply.")).toEqual({
      message: "The part doesn't fit on the plate.",
      kind: "fit",
    })
    expect(plainSliceError("No filaments are loaded. Ask the user which colours are in the CFS slots").kind).toBe("colour")
    expect(plainSliceError("something odd").message).toBe("Slicing didn't work.")
  })

  it("a recorded failure shows on the overview until the design changes", async () => {
    const id = await designedProject("Slice error")
    recordSliceError(id, "OrcaSlicer failed (exit 206): plate 1: Nothing to be sliced, Either the print is empty or no object is fully inside the print volume before apply.")
    let o = await projectOverview(id)
    expect(o.slice.error).toMatchObject({ message: "The part doesn't fit on the plate." })
    expect(o.slice.error?.detail).toMatch(/exit 206/)
    writeFileSync(join(store.projectDir(id), "parts/main.scad"), "cube([10, 10, 10]);\n")
    expect(currentSliceError(id)).toBeNull()
    o = await projectOverview(id)
    expect(o.slice.error ?? null).toBeNull()
  })
})

describe("practice prints aren't rated", () => {
  it("a finished practice print is not offered for rating after a reconnect", () => {
    const rec = {
      id: "p1",
      projectId: "x",
      machineId: practiceId,
      partIds: [],
      gcodeName: "a.gcode",
      printerFilename: null,
      startedAt: new Date().toISOString(),
      finishedAt: new Date().toISOString(),
      state: "complete" as const,
      result: null,
      notes: null,
      estimatedTimeS: null,
      filamentG: null,
    }
    expect(printer.isPracticePrint(rec)).toBe(true)
    expect(printer.isPracticePrint({ machineId: "garage" })).toBe(false)
    // sync filters practice prints out before unratedPrints
    expect(unratedPrints([rec].filter((p) => !printer.isPracticePrint(p)))).toEqual([])
  })
})

describe.skipIf(!existsSync(ORCA) || !existsSync(OPENSCAD))("with the real slicer", () => {
  it("a template that declares Black (no color() in the source) slices with the Black slot, not slot 1", { timeout: 300_000 }, async () => {
    const { slicePart } = await import("../slicer/index")
    const p = await store.createProjectFromStarter(join(__dirname, "../../resources/starters/phone-stand"), "Phone stand colour")
    await store.updateProject(p.id, { printer: practiceId })
    const r = await slicePart(p.id, "stand")
    expect(r.filamentBySlot?.map((s) => s.colorName)).toEqual(["Black"])
    const { request } = await printer.createPrintRequest(p.id, r.gcodePath, "user")
    expect(request.designColors).toEqual(["black"])
    expect(request.slotFilaments?.map((f) => f.colorName)).toEqual(["Black"])
    await printer.answerPrintRequest(request.requestId, false, false)
  })

  it("a part too big for the printer: the overview says Make it fit before slicing; a forced slice failure is kept in plain words", { timeout: 300_000 }, async () => {
    const { slicePart } = await import("../slicer/index")
    const id = await designedProject("Too big")
    writeFileSync(join(store.projectDir(id), "parts/main.scad"), "cube([400, 40, 10]);\n")
    const { renderPart } = await import("../cad/index")
    await renderPart(id, "main")
    const o = await projectOverview(id)
    expect(o.next).toMatchObject({ kind: "fit", label: "Make it fit" })
    expect(o.next.detail).toMatch(/^Too big for Practice printer: 400 mm wide, max \d+ mm\.$/)
    await expect(slicePart(id, "main")).rejects.toThrow()
    expect(currentSliceError(id)).toMatchObject({ kind: "fit", message: "The part doesn't fit on the plate." })
  })
})
